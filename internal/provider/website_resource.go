var (
	_ resource.Resource                = &WebsiteResource{}
	_ resource.ResourceWithImportState = &WebsiteResource{}
	_ resource.ResourceWithModifyPlan  = &WebsiteResource{}
)

func NewWebsiteResource() resource.Resource {
	return &WebsiteResource{}
}

type WebsiteResource struct {
	client *Client
}

func (r *WebsiteResource) Metadata(ctx context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_website"
}

func (r *WebsiteResource) Schema(ctx context.Context, req resource.SchemaRequest, resp *resource.SchemaResponse) {
	resp.Schema = schema.Schema{
		MarkdownDescription: "A website tracked by Umami. The website ID is what the tracker script needs in `data-website-id`. See [documentation](https://docs.umami.is/docs/api/websites) for more details.",

		Attributes: map[string]schema.Attribute{
			"id": schema.StringAttribute{
				MarkdownDescription: "ID (UUID) of the website. Set it to know the ID at plan time, e.g. `uuidv5(\"dns\", \"example.com\")`. It must be an RFC 4122 UUID, which `random_uuid` does not reliably produce. Generated by Umami when omitted. Changing it forces a new website, which loses its analytics history.",
				Optional:            true,
				Computed:            true,
				PlanModifiers: []planmodifier.String{
					stringplanmodifier.UseStateForUnknown(),
					stringplanmodifier.RequiresReplace(),
				},
				Validators: []validator.String{
					stringvalidator.RegexMatches(uuidRegex, "must be an RFC 4122 UUID, e.g. from uuidv5()"),
				},
			},
			"name": schema.StringAttribute{
				MarkdownDescription: "Display name of the website.",
				Required:            true,
				Validators:          []validator.String{stringvalidator.LengthBetween(1, 100)},
			},
			"domain": schema.StringAttribute{
				MarkdownDescription: "Domain of the website, without scheme or path, e.g. `example.com`. Umami uses it as a label only and does not restrict where events come from.",
				Required:            true,
				Validators: []validator.String{
					stringvalidator.LengthAtMost(500),
					stringvalidator.RegexMatches(domainRegex, "must be a lowercase domain such as example.com, without scheme or path"),
				},
			},
			"team_id": schema.StringAttribute{
				MarkdownDescription: "ID of the team that owns the website. When omitted, the website belongs to the authenticated user. Changing it transfers the website and keeps its data. Without admin rights, moving a website out of a team requires the team-owner role in that team.",
				Optional:            true,
				Validators: []validator.String{
					stringvalidator.RegexMatches(uuidRegex, "must be a UUID"),
				},
			},
			"user_id": schema.StringAttribute{
				MarkdownDescription: "ID of the user that owns the website, or null when a team owns it.",
				Computed:            true,
			},
			"created_by": schema.StringAttribute{
				MarkdownDescription: "ID of the user that created the website.",
				Computed:            true,
				PlanModifiers:       []planmodifier.String{stringplanmodifier.UseStateForUnknown()},
			},
			"created_at": schema.StringAttribute{
				MarkdownDescription: "Creation timestamp (RFC 3339).",
				Computed:            true,
				PlanModifiers:       []planmodifier.String{stringplanmodifier.UseStateForUnknown()},
			},
		},
	}
}

func (r *WebsiteResource) Configure(ctx context.Context, req resource.ConfigureRequest, resp *resource.ConfigureResponse) {
	if client := configureResource(req, resp); client != nil {
		r.client = client
	}
}

func (r *WebsiteResource) ModifyPlan(ctx context.Context, req resource.ModifyPlanRequest, resp *resource.ModifyPlanResponse) {
	if req.State.Raw.IsNull() || req.Plan.Raw.IsNull() {
		return
	}

	var plan, state WebsiteModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	if plan.TeamID.Equal(state.TeamID) {
		resp.Diagnostics.Append(resp.Plan.SetAttribute(ctx, path.Root("user_id"), state.UserID)...)
	}
}

func (r *WebsiteResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan WebsiteModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}

	created, err := r.client.CreateWebsite(ctx, expandCreateWebsiteRequest(plan))
	if err != nil {
		resp.Diagnostics.AddError("Error Creating Website", fmt.Sprintf("Could not create website: %s", err))
		return
	}

	website, err := r.client.GetWebsite(ctx, created.ID)
	if err != nil {
		if cleanupErr := r.client.DeleteWebsite(ctx, created.ID); cleanupErr != nil {
			tflog.Warn(ctx, "Failed to clean up website after create failure", map[string]any{"id": created.ID, "error": cleanupErr.Error()})
			resp.Diagnostics.AddWarning(
				"Website Create Rollback Failed",
				fmt.Sprintf("Website %s was created but could not be read back or deleted: %s. Delete it manually or import it.", created.ID, cleanupErr),
			)
		}
		resp.Diagnostics.AddError("Error Reading Website", fmt.Sprintf("Could not read website ID %s: %s", created.ID, err))
		return
	}

	state := flattenWebsite(website)
	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

func (r *WebsiteResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state WebsiteModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	website, err := r.client.GetWebsite(ctx, state.ID.ValueString())
	if err != nil {
		if isNotFoundError(err) {
			resp.State.RemoveResource(ctx)
			return
		}
		resp.Diagnostics.AddError("Error Reading Website", fmt.Sprintf("Could not read website ID %s: %s", state.ID.ValueString(), err))
		return
	}

	state = flattenWebsite(website)
	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

func (r *WebsiteResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan, state WebsiteModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	id := state.ID.ValueString()

	if !plan.TeamID.Equal(state.TeamID) {
		if err := r.transfer(ctx, id, plan.TeamID); err != nil {
			resp.Diagnostics.AddError("Error Transferring Website", fmt.Sprintf("Could not transfer website ID %s: %s", id, err))
			return
		}
	}

	body := UpdateWebsiteRequest{Name: plan.Name.ValueString(), Domain: plan.Domain.ValueString()}
	if _, err := r.client.UpdateWebsite(ctx, id, body); err != nil {
		resp.Diagnostics.AddError("Error Updating Website", fmt.Sprintf("Could not update website ID %s: %s", id, err))
		return
	}

	website, err := r.client.GetWebsite(ctx, id)
	if err != nil {
		resp.Diagnostics.AddError("Error Reading Website", fmt.Sprintf("Could not read website ID %s: %s", id, err))
		return
	}

	newState := flattenWebsite(website)
	resp.Diagnostics.Append(resp.State.Set(ctx, &newState)...)
}

// Non-admins cannot move a website between teams directly, so it goes through the user first.
func (r *WebsiteResource) transfer(ctx context.Context, id string, to types.String) error {
	current, err := r.client.GetWebsite(ctx, id)
	if err != nil {
		return err
	}
	if types.StringPointerValue(current.TeamID).Equal(to) {
		return nil
	}
	if current.TeamID != nil {
		me, err := r.client.GetMe(ctx)
		if err != nil {
			return fmt.Errorf("could not look up the authenticated user: %w", err)
		}
		if err := r.client.TransferWebsite(ctx, id, "", me.User.ID); err != nil {
			return err
		}
	}
	if to.IsNull() {
		return nil
	}
	return r.client.TransferWebsite(ctx, id, to.ValueString(), "")
}

func (r *WebsiteResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var state WebsiteModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	id := state.ID.ValueString()
	if err := r.client.DeleteWebsite(ctx, id); err != nil {
		if _, getErr := r.client.GetWebsite(ctx, id); isNotFoundError(getErr) {
			return
		}
		resp.Diagnostics.AddError("Error Deleting Website", fmt.Sprintf("Could not delete website ID %s: %s", id, err))
	}
}

func (r *WebsiteResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	resource.ImportStatePassthroughID(ctx, path.Root("id"), req, resp)
}
