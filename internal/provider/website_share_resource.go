var (
	_ resource.Resource                = &WebsiteShareResource{}
	_ resource.ResourceWithImportState = &WebsiteShareResource{}
)

var shareSlugRegex = regexp.MustCompile(`^[A-Za-z0-9_-]+$`)

func NewWebsiteShareResource() resource.Resource {
	return &WebsiteShareResource{}
}

type WebsiteShareResource struct {
	client *Client
}

func (r *WebsiteShareResource) Metadata(ctx context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_website_share"
}

func (r *WebsiteShareResource) Schema(ctx context.Context, req resource.SchemaRequest, resp *resource.SchemaResponse) {
	resp.Schema = schema.Schema{
		MarkdownDescription: "A public share link for a website's dashboard, served at `<umami url>/share/<slug>`. Anyone with the link can view the selected pages without logging in. A website can have several shares.",

		Attributes: map[string]schema.Attribute{
			"id": schema.StringAttribute{
				MarkdownDescription: "ID of the share, in the form `website_id/share_id`.",
				Computed:            true,
				PlanModifiers:       []planmodifier.String{stringplanmodifier.UseStateForUnknown()},
			},
			"website_id": schema.StringAttribute{
				MarkdownDescription: "ID of the website to share.",
				Required:            true,
				PlanModifiers:       []planmodifier.String{stringplanmodifier.RequiresReplace()},
				Validators:          []validator.String{stringvalidator.RegexMatches(uuidRegex, "must be a UUID")},
			},
			"name": schema.StringAttribute{
				MarkdownDescription: "Name of the share, shown in the website settings.",
				Required:            true,
				Validators:          []validator.String{stringvalidator.LengthBetween(1, 200)},
			},
			"slug": schema.StringAttribute{
				MarkdownDescription: "Path segment of the share URL. Slugs are unique across the Umami instance. Generated by Umami when omitted.",
				Optional:            true,
				Computed:            true,
				PlanModifiers:       []planmodifier.String{stringplanmodifier.UseStateForUnknown()},
				Validators: []validator.String{
					stringvalidator.LengthBetween(1, 100),
					stringvalidator.RegexMatches(shareSlugRegex, "must contain only letters, digits, hyphens and underscores"),
				},
			},
			"views": schema.SetAttribute{
				MarkdownDescription: "Pages the share exposes. One or more of `" + strings.Join(shareViews, "`, `") + "`. Defaults to `overview` and `events`, as in the Umami UI.",
				ElementType:         types.StringType,
				Optional:            true,
				Computed:            true,
				Default: setdefault.StaticValue(types.SetValueMust(types.StringType, []attr.Value{
					types.StringValue("overview"), types.StringValue("events"),
				})),
				Validators: []validator.Set{
					setvalidator.SizeAtLeast(1),
					setvalidator.ValueStringsAre(stringvalidator.OneOf(shareViews...)),
				},
			},
			"allow_filter": schema.BoolAttribute{
				MarkdownDescription: "Whether viewers can filter the shared data. Defaults to `true`.",
				Optional:            true,
				Computed:            true,
				Default:             booldefault.StaticBool(true),
			},
			"theme": schema.StringAttribute{
				MarkdownDescription: "Theme of the shared page, `light` or `dark`. Follows the viewer's system setting when omitted.",
				Optional:            true,
				Validators:          []validator.String{stringvalidator.OneOf("light", "dark")},
			},
			"created_at": schema.StringAttribute{
				MarkdownDescription: "Creation timestamp (RFC 3339).",
				Computed:            true,
				PlanModifiers:       []planmodifier.String{stringplanmodifier.UseStateForUnknown()},
			},
		},
	}
}

func (r *WebsiteShareResource) Configure(ctx context.Context, req resource.ConfigureRequest, resp *resource.ConfigureResponse) {
	if client := configureResource(req, resp); client != nil {
		r.client = client
	}
}

func (r *WebsiteShareResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan WebsiteShareModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}

	body, diags := expandShareRequest(ctx, plan)
	if resp.Diagnostics.Append(diags...); resp.Diagnostics.HasError() {
		return
	}
	body.EntityID = plan.WebsiteID.ValueString()
	body.ShareType = shareTypeWebsite

	created, err := r.client.CreateShare(ctx, body)
	if err != nil {
		resp.Diagnostics.AddError("Error Creating Website Share", fmt.Sprintf("Could not create a share for website %s: %s", body.EntityID, err))
		return
	}

	if state := r.read(ctx, body.EntityID, created.ID, &resp.Diagnostics); state != nil {
		resp.Diagnostics.Append(resp.State.Set(ctx, state)...)
	}
}

func (r *WebsiteShareResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state WebsiteShareModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	websiteID, shareID := splitWebsiteShareID(state.ID.ValueString())
	share, err := r.client.GetWebsiteShare(ctx, websiteID, shareID)
	if err != nil {
		if isNotFoundError(err) {
			resp.State.RemoveResource(ctx)
			return
		}
		resp.Diagnostics.AddError("Error Reading Website Share", fmt.Sprintf("Could not read share %s: %s", state.ID.ValueString(), err))
		return
	}

	newState, diags := flattenWebsiteShare(share)
	resp.Diagnostics.Append(diags...)
	resp.Diagnostics.Append(resp.State.Set(ctx, &newState)...)
}

func (r *WebsiteShareResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan, state WebsiteShareModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	body, diags := expandShareRequest(ctx, plan)
	if resp.Diagnostics.Append(diags...); resp.Diagnostics.HasError() {
		return
	}
	if body.Slug == "" {
		body.Slug = state.Slug.ValueString()
	}

	websiteID, shareID := splitWebsiteShareID(state.ID.ValueString())
	if _, err := r.client.UpdateShare(ctx, shareID, body); err != nil {
		resp.Diagnostics.AddError("Error Updating Website Share", fmt.Sprintf("Could not update share %s: %s", state.ID.ValueString(), err))
		return
	}

	if newState := r.read(ctx, websiteID, shareID, &resp.Diagnostics); newState != nil {
		resp.Diagnostics.Append(resp.State.Set(ctx, newState)...)
	}
}

func (r *WebsiteShareResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var state WebsiteShareModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	websiteID, shareID := splitWebsiteShareID(state.ID.ValueString())
	if err := r.client.DeleteShare(ctx, shareID); err != nil {
		if _, getErr := r.client.GetWebsiteShare(ctx, websiteID, shareID); isNotFoundError(getErr) {
			return
		}
		resp.Diagnostics.AddError("Error Deleting Website Share", fmt.Sprintf("Could not delete share %s: %s", state.ID.ValueString(), err))
	}
}

func (r *WebsiteShareResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	websiteID, shareID := splitWebsiteShareID(req.ID)
	if !uuidRegex.MatchString(websiteID) || !uuidRegex.MatchString(shareID) {
		resp.Diagnostics.AddError("Invalid Import ID", fmt.Sprintf("Expected website_id/share_id, got %q.", req.ID))
		return
	}
	resource.ImportStatePassthroughID(ctx, path.Root("id"), req, resp)
}

func (r *WebsiteShareResource) read(ctx context.Context, websiteID, shareID string, diags *diag.Diagnostics) *WebsiteShareModel {
	share, err := r.client.GetWebsiteShare(ctx, websiteID, shareID)
	if err != nil {
		diags.AddError("Error Reading Website Share", fmt.Sprintf("Could not read share %s: %s", websiteShareID(websiteID, shareID), err))
		return nil
	}
	model, d := flattenWebsiteShare(share)
	diags.Append(d...)
	return &model
}

func splitWebsiteShareID(id string) (string, string) {
	websiteID, shareID, _ := strings.Cut(id, "/")
	return websiteID, shareID
}
